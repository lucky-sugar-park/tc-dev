-- 누가·언제·어디서·무엇을·어떻게 바꿨는지와 변경 전·후 값(JSON, 비밀값은 가림)을 남긴다.
-- ddl-auto=update 인 환경은 앱이 기동할 때 만든다. ddl-auto 를 끈 운영 DB 에는 이 스크립트를 먼저 돌린다. 대상 DB: tc

SET SESSION lock_wait_timeout = 10;

CREATE TABLE IF NOT EXISTS config_change_hist (
    ID             VARCHAR(36)  NOT NULL,
    CHANGED_AT     DATETIME(6)  NOT NULL,
    ACTOR_TYPE     VARCHAR(20)  NOT NULL,   -- USER, API_CLIENT, SYSTEM
    ACTOR_ID       VARCHAR(200) NOT NULL,
    ACTOR_IP       VARCHAR(64)  NULL,
    TARGET_TYPE    VARCHAR(30)  NOT NULL,   -- PLC_CONNECTOR, INTERFACE, WEBHOOK, DELIVERY, SCHEDULE_JOB, USER, API_CLIENT, API_KEY, OPTION
    TARGET_ID      VARCHAR(200) NOT NULL,
    TARGET_NAME    VARCHAR(200) NULL,
    ACTION         VARCHAR(20)  NOT NULL,   -- CREATE, UPDATE, DELETE, ENABLE, DISABLE, CONTROL
    DETAIL         VARCHAR(100) NULL,
    BEFORE_JSON    LONGTEXT     NULL,
    AFTER_JSON     LONGTEXT     NULL,
    TRANSACTION_ID VARCHAR(100) NULL,
    PRIMARY KEY (ID),
    INDEX IX_CONFIG_CHANGE_TARGET (TARGET_TYPE, TARGET_ID, CHANGED_AT),
    INDEX IX_CONFIG_CHANGE_ACTOR (ACTOR_ID, CHANGED_AT),
    INDEX IX_CONFIG_CHANGE_AT (CHANGED_AT)
);
